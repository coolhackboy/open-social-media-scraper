#!/usr/bin/env node
/**
 * Refreshes the "Supported platforms" table in README.md from src/data/catalog.json.
 * Usage: node scripts/readme-platforms.mjs
 */
import fs from 'node:fs';
import path from 'node:path';
import { ROOT } from './lib/sources.mjs';

const catalog = JSON.parse(fs.readFileSync(path.join(ROOT, 'src/data/catalog.json'), 'utf8'));
const readme = path.join(ROOT, 'README.md');
const UTM = 'utm_source=open-social-media-scraper&utm_medium=readme';

const fmt = (b) => {
  const n = (v) => (Number.isInteger(v) ? String(v) : String(Number(v.toFixed(4))));
  if (b.mode === 'fixed') return `${n(b.baseCredits)} cr / request`;
  const unit = b.mode === 'input_count' ? 'keyword' : 'result';
  const per = b.mode === 'input_count' ? b.unitCredits : b.resultUnitCredits;
  return `${b.baseCredits ? `${n(b.baseCredits)} + ` : ''}${n(per)} cr / ${unit}`;
};

const rows = catalog.platforms.map((p) => {
  const eps = catalog.endpoints.filter((e) => e.platform === p.id).sort((a, b) => a.hotRank - b.hotRank);
  const top = eps
    .slice(0, 4)
    .map((e) => `[${e.name.replace(new RegExp(`^${p.title}\\s+`, 'i'), '')}](https://docs.socq.ai/api-manual/${e.id}?${UTM})`)
    .join(', ');
  const cheapest = eps.map((e) => e.billing).sort((a, b) => (a.resultUnitCredits ?? a.unitCredits ?? a.baseCredits) - (b.resultUnitCredits ?? b.unitCredits ?? b.baseCredits))[0];
  return `| ${p.title} | ${p.count} | ${top}${eps.length > 4 ? ', …' : ''} | from ${fmt(cheapest)} |`;
});

const block = [
  '<!-- platforms:start -->',
  '<!-- Generated by scripts/readme-platforms.mjs — do not edit by hand. -->',
  '',
  `**${catalog.counts.endpoints} endpoints across ${catalog.counts.platforms} platforms** · catalog snapshot ${catalog.generatedAt.slice(0, 10)}. 1 credit = $${catalog.creditUSD}.`,
  'Prices are SocQ list prices at snapshot time; the app shows an estimate for your exact request and the actual charge afterwards.',
  '',
  '| Platform | Endpoints | Examples | Price |',
  '| --- | ---: | --- | --- |',
  ...rows,
  '',
  '<!-- platforms:end -->',
].join('\n');

const text = fs.readFileSync(readme, 'utf8');
const next = text.replace(/<!-- platforms:start -->[\s\S]*<!-- platforms:end -->/, block);
if (next === text && !text.includes('<!-- platforms:start -->')) {
  console.error('README.md has no <!-- platforms:start --> marker');
  process.exit(1);
}
fs.writeFileSync(readme, next);
console.log(`README.md: ${rows.length} platforms`);
